def _as_sequence(value):
    """Normalize a generated action factory result into one flat workflow."""
    return value if isinstance(value, list) else [value]


def _pick_and_return_tip_workflow():
    """Build the native OT-2 A1 pickup, hold, return, and physics release demo."""
    from unitelabs.opentrons_ot2.matterix.actions import PickUpTipCfg, ReturnTipCfg

    from .matterix_ot2_actions import build_ot2_action_cfg

    from unitelabs.opentrons_ot2.matterix.asset import OT2MatterixAssetConfig

    binding = OT2MatterixAssetConfig.from_file(_matterix_config_path()).tip_rack_bindings[0]
    pickup = build_ot2_action_cfg(
        PickUpTipCfg(mount=binding.mount, labware_id=binding.labware_id, well="A1")
    )
    return_tip = build_ot2_action_cfg(
        ReturnTipCfg(mount=binding.mount, labware_id=binding.labware_id, well="A1")
    )
    return [*_as_sequence(pickup), WaitCfg(duration=1.0), *_as_sequence(return_tip)]



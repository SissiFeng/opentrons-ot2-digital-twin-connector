def _matterix_config_path():
    candidates = [
        os.environ.get("OT2_MATTERIX_CONFIG", ""),
        str(Path(__file__).resolve().parents[1] / "config" / "matterix_ot2.json"),
        "config/matterix_ot2.json",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            return Path(candidate)
    raise FileNotFoundError(
        "OT-2 Matterix config not found; set OT2_MATTERIX_CONFIG to the pinned "
        "config/matterix_ot2.json containing verified joint alignment."
    )


def _aligned_ot2_cfg():
    """Apply verified joint and base-frame alignment to the OT-2 articulation."""
    if OT2_CFG is None or apply_ot2_joint_alignment is None:
        return None
    from unitelabs.opentrons_ot2.matterix.asset import OT2MatterixAssetConfig

    asset = OT2MatterixAssetConfig.from_file(_matterix_config_path())
    asset.validate_joint_alignment()
    asset.validate_reference_frame_alignment()
    world_from_base = asset.reference_frame_alignment.world_from_base
    cfg = OT2_CFG(pos=world_from_base.translation_m)
    cfg.init_state.rot = world_from_base.transform_orientation(cfg.init_state.rot)
    binding = asset.tip_rack_bindings[0]
    cfg.semantics = [
        IsTipAttachedCfg(default_tip_asset_name=binding.asset_name),
        Ot2TipAttachmentCfg(ee_sensor_name=binding.ee_sensor_name),
    ]
    return apply_ot2_joint_alignment(cfg, asset.joint_alignment)


def _tip_rack_cfgs():
    """Place accepted nested tip racks from connector deck coordinates."""
    if OT2_TIP_RACK_CFG is None or make_ot2_tip_rack_with_tips_cfg is None:
        return {}
    from unitelabs.opentrons_ot2.digital_twin.config import DigitalTwinConfig
    from unitelabs.opentrons_ot2.matterix.asset import OT2MatterixAssetConfig

    connector_candidates = [
        os.environ.get("OT2_CONNECTOR_CONFIG", ""),
        str(Path(__file__).resolve().parents[1] / "config" / "ot2_dt_config.json"),
        "config/ot2_dt_config.json",
    ]
    connector_path = next(
        (Path(candidate) for candidate in connector_candidates if candidate and Path(candidate).is_file()),
        None,
    )
    if connector_path is None:
        raise FileNotFoundError("OT-2 connector config not found; set OT2_CONNECTOR_CONFIG")
    connector = DigitalTwinConfig.from_file(connector_path)
    asset = OT2MatterixAssetConfig.from_file(_matterix_config_path())
    asset.validate_reference_frame_alignment()
    asset.validate_tip_rack_bindings(connector)
    world_from_deck = asset.reference_frame_alignment.world_from_deck
    result = {}
    for binding in asset.tip_rack_bindings:
        placement = connector.placement(binding.labware_id)
        position = asset.reference_frame_alignment.deck_point_mm_to_world_m(
            (placement.origin.x, placement.origin.y, placement.origin.z)
        )
        rack_cfg = OT2_TIP_RACK_CFG(pos=position)
        rack_cfg.rot = world_from_deck.rotation_wxyz
        cfg = make_ot2_tip_rack_with_tips_cfg()
        cfg.pos = position
        cfg.rot = world_from_deck.rotation_wxyz
        result[f"{binding.asset_name}_rack"] = rack_cfg
        result[binding.asset_name] = cfg
    return result



def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    check = subparsers.add_parser("check", help="Run non-launching Matterix OT-2 readiness checks.")
    check.add_argument("--connector-config", default="config/ot2_dt_config.json")
    check.add_argument("--matterix-config", default="config/matterix_ot2.json")
    check.add_argument("--json", action="store_true", help="Emit a machine-readable report.")
    check.add_argument("--strict", action="store_true", help="Exit 1 when any check is missing.")

    generate = subparsers.add_parser("generate", help="Generate a Matterix OT-2 task extension scaffold.")
    generate.add_argument("directory", help="Target directory for the generated extension.")
    generate.add_argument("--matterix-config", default="config/matterix_ot2.json")
    generate.add_argument("--force", action="store_true", help="Overwrite existing files.")

    return parser


def _cmd_check(args: argparse.Namespace) -> int:
    try:
        validation: EnvironmentValidation = validate_environment(
            args.connector_config,
            args.matterix_config,
        )
    except MatterixEnvironmentError as error:
        sys.stderr.write(f"error: {error}\n")
        return 1
    payload = {
        "ready": validation.ready,
        "checks": [check.to_mapping() for check in validation.checks],
    }
    if args.json:
        sys.stdout.write(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    else:
        lines = [f"[{check.status}] {check.name}: {check.detail}" for check in validation.checks]
        lines += [f"  fix: {check.remedy}" for check in validation.checks if not check.ok and check.remedy]
        lines.append("Summary: ready" if validation.ready else "Summary: Matterix OT-2 env is not ready")
        sys.stdout.write("\n".join(lines) + "\n")
    return 0 if validation.ready or not args.strict else 1


def _cmd_generate(args: argparse.Namespace) -> int:
    target = Path(args.directory)
    try:
        asset = OT2MatterixAssetConfig.from_file(args.matterix_config)
    except MatterixAssetConfigurationError as error:
        sys.stderr.write(f"error: {error}\n")
        return 1

    files = {
        "matterix_ot2_env.py": _ENV_MODULE,
        "matterix_ot2_actions.py": _ACTIONS_MODULE,
        "__init__.py": "# Matterix OT-2 task extension (generated).\n",
        "README.md": (
            "# Matterix OT-2 task extension\n\n"
            f"Task id: `{asset.task_id}`\n\n"
            "Install this package into the Matterix Isaac Lab environment, then\n"
            "`import matterix_tasks` (or this module) before `gym.make(...)`.\n\n"
            "## Ubuntu verification\n\n"
            "```sh\n"
            'cd ~/matterix-internal && export MATTERIX_PATH="$PWD"\n'
            "git -C source/matterix_assets/data submodule update --init --remote\n"
            "./matterix.sh -p scripts/random_agent.py --task Matterix-OT2-LiquidHandler-v1 --num_envs 256 --headless\n"
            "./matterix.sh -p scripts/random_agent.py --task Matterix-OT2-LiquidHandler-v1 --num_envs 1024 --headless\n"
            "```\n\n"
            "## Action factory\n\n"
            "`matterix_ot2_actions.py` implements `build_ot2_action_cfg(action)`;\n"
            "point `OT2_CONNECTOR_CONFIG` at the pinned `config/ot2_dt_config.json`.\n"
        ),
    }
    try:
        target.mkdir(parents=True, exist_ok=True)
        for name, content in files.items():
            path = target / name
            if path.exists() and not args.force:
                sys.stderr.write(f"skip (exists, use --force): {path}\n")
                continue
            path.write_text(content, encoding="utf-8")
            sys.stdout.write(f"wrote {path}\n")
    except OSError as error:
        sys.stderr.write(f"error: {error}\n")
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    """Dispatch the check/generate subcommands."""
    args = _parser().parse_args(argv)
    if args.command == "check":
        return _cmd_check(args)
    if args.command == "generate":
        return _cmd_generate(args)
    _parser().print_help(sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())

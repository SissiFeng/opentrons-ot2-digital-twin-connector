def _load_connector():
    """Load the pinned OT-2 connector deck config used for well resolution."""
    from unitelabs.opentrons_ot2.digital_twin.config import DigitalTwinConfig

    candidates = [
        os.environ.get("OT2_CONNECTOR_CONFIG", ""),
        str(Path(__file__).resolve().parents[1] / "config" / "ot2_dt_config.json"),
        "config/ot2_dt_config.json",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            return DigitalTwinConfig.from_file(candidate)
    raise FileNotFoundError(
        "OT-2 connector config not found; set OT2_CONNECTOR_CONFIG to the "
        "pinned config/ot2_dt_config.json used by the connector."
    )


def _load_asset(connector=None):
    """Load the pinned executable Matterix OT-2 integration contract."""
    from unitelabs.opentrons_ot2.matterix.asset import OT2MatterixAssetConfig

    candidates = [
        os.environ.get("OT2_MATTERIX_CONFIG", ""),
        str(Path(__file__).resolve().parents[1] / "config" / "matterix_ot2.json"),
        "config/matterix_ot2.json",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            config = OT2MatterixAssetConfig.from_file(candidate)
            config.validate_joint_alignment()
            config.validate_reference_frame_alignment()
            config.validate_tip_rack_bindings(connector or _load_connector())
            return config
    raise FileNotFoundError(
        "OT-2 Matterix config not found; set OT2_MATTERIX_CONFIG to the pinned "
        "config/matterix_ot2.json containing verified joint alignment."
    )


def _joint_move_cfg(move) -> object:
    """Build the Matterix joint-space move config for one OT-2 move."""
    try:
        from matterix_sm.primitive_actions.move_to_joint_config import MoveToJointConfigCfg
    except ImportError as error:
        raise ImportError(
            "OT-2 joint-space moves require the Matterix MoveToJointConfig "
            "primitive (matterix_sm/primitive_actions/move_to_joint_config.py); "
            "see OT2_MATTERIX_PORT_PLAN.md."
        ) from error
    return MoveToJointConfigCfg(
        agent_assets=move.agent_assets,
        action_space_info=OT2_JOINT_ACTION_SPACE,
        target_joint_positions=move.target_joint_positions,
        joint_indices=move.joint_indices,
        position_threshold=move.position_threshold,
        settling_time=move.settling_time,
    )


def build_ot2_action_cfg(action):
    """Translate one connector OT-2 semantic action into matterix_sm configs.

    One connector action may map to multiple primitives (e.g. PickUpTip =
    move + tip-presence semantic).  A single config is returned for
    one-to-one translations, otherwise a list of configs is returned
    (StateMachine.set_action_sequence accepts both).
    """
    from unitelabs.opentrons_ot2.matterix.actions_runtime import (
        MatterixMoveToJointConfig,
        MatterixSemanticAction,
        MatterixWait,
        translate_action,
    )

    connector = _load_connector()
    asset = _load_asset(connector)
    translated = translate_action(
        action,
        connector=connector,
        alignment=asset.joint_alignment,
        agent_asset="ot2",
        tip_rack_bindings=asset.tip_rack_bindings,
    )

    configs = []
    for cfg in translated.configs:
        if isinstance(cfg, MatterixMoveToJointConfig):
            configs.append(_joint_move_cfg(cfg))
        elif isinstance(cfg, MatterixSemanticAction):
            configs.append(
                SemanticActionCfg(
                    semantics=[
                        SemanticInfo(
                            type=item.type,
                            asset_name=item.asset_name,
                            value=item.value,
                            additional_info=dict(item.additional_info),
                        )
                        for item in cfg.semantics
                    ]
                )
            )
        elif isinstance(cfg, MatterixWait):
            configs.append(WaitCfg(duration=cfg.duration))
        else:
            raise ValueError(f"Unsupported translated OT-2 config: {cfg!r}")
    if not configs:
        raise ValueError(f"OT-2 action translation produced no configs: {action!r}")
    return configs[0] if len(configs) == 1 else configs
